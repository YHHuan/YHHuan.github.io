const pages = [
  ["index.html", "About", "黃彥勛 Yen-Hsun Huang: PGY-2 physician in Taipei working on digital devices, occupational health, clinical data, and evidence synthesis.", about],
  ["research.html", "Research", "Wearable devices, firefighter health, clinical cohorts, EEG, smart glasses, and evidence synthesis projects by Yen-Hsun Huang.", research],
  ["publications.html", "Publications", "Peer-reviewed journal articles, preprints, and ongoing manuscripts by Yen-Hsun Huang, M.D.", publications],
  ["conferences.html", "Conferences & teaching", "Accepted posters, conference presentations, and teaching by Yen-Hsun Huang, including ICOH, ASPA, and Neuroscience.", conferences],
  ["experience.html", "Experience & awards", "Education, clinical and research experience, honors, student activities, and skills of Yen-Hsun Huang.", experience],
];
const outputs = new Map(pages.map(([file,title,desc,body]) => [file, document(file,title,desc,body)]));
outputs.set("sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${pages.map(([f]) => `  <url><loc>https://yhhuan.github.io/${f === "index.html" ? "" : f}</loc><lastmod>${c.updated}</lastmod></url>`).join("\n")}\n</urlset>\n`);
for (const [file, output] of outputs) {
  if (process.argv.includes("--check")) {
    if (await readFile(new URL(file, root), "utf8").catch(() => "") !== output) throw new Error(`Stale generated file: ${file}. Run node scripts/build.mjs`);
  } else {
    await writeFile(new URL(file, root), output);
  }
}
console.log(`${process.argv.includes("--check") ? "Checked" : "Generated"} ${pages.length} pages and sitemap.`);
